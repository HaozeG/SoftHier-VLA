#!/bin/bash
# Run one hand-written kernel once on the patched GVSoC, with optional traces.
#
#   run_kernel.sh <kernel> <kernel_cfg.py> <out_dir> [--trace] [--hbm] [--arch <arch.py>]
#
#   kernel: elt | gemm | attn | acti | lnorm | norm
#   arch:   default infra/kernel-runs/arch/arch_h1.py (stage-1 H1)
#   out_dir receives: kernel_cfg.py, arch.py, sim_stamp.json (which simulator build ran), the generated
#   kernel headers and preload.elf, build.log, run.log (timer line and output check); with --trace
#   runv.log, pfto.log, perfetto.json; with --hbm hbm_ctrl.log.gz and hbm_channels.txt (per channel).
#
# The simulator is never built here. It comes from $SOFTHIER_HOME (infra/env.sh) and must pass
# `stamp.py check <arch>` (infra/softhier/require_sim.sh): upstream soft_hier_release plus the GVSoC patch
# series, built for this arch with infra/softhier/build_arch.sh. The script holds the tree's lock for the
# whole run. KREPO (env) is the kernel source, default the submodule third_party/softhier-kernels; only its
# implementation/ folder is used.
# Spec: docs/designs/stage1-spec.md §4.3 (measurement protocol).
set -euo pipefail

HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
KERNEL=$1; CFG=$(realpath "$2"); OUT=$3; shift 3
TRACE=0
HBM=0
ARCH=$HERE/arch/arch_h1.py
KREPO=${KREPO:-$HERE/../../third_party/softhier-kernels}
while [ $# -gt 0 ]; do
  case $1 in
    --trace) TRACE=1; shift ;;
    --hbm) HBM=1; shift ;;
    --arch) ARCH=$(realpath "$2"); shift 2 ;;
    *) echo "unknown option $1" >&2; exit 2 ;;
  esac
done

case $KERNEL in
  elt) APP=Eltwise ;; gemm) APP=SummaGEMM ;; attn) APP=FlatAttention ;;
  acti) APP=Activation ;; lnorm) APP=LayerNorm ;; norm) APP=RMSNorm ;;
  *) echo "unknown kernel $KERNEL" >&2; exit 2 ;;
esac
IMPL=$KREPO/implementation
mkdir -p "$OUT"; OUT=$(realpath "$OUT")

# shellcheck source=../softhier/require_sim.sh
. "$HERE/../softhier/require_sim.sh"
sim_lock
require_sim "$ARCH" "$OUT"
SH=$SOFTHIER_HOME

cp "$CFG" "$OUT/kernel_cfg.py"; cp "$ARCH" "$OUT/arch.py"
git -C "$KREPO" rev-parse HEAD > "$OUT/kernel_repo_commit.txt"
git -C "$KREPO" diff --stat HEAD >> "$OUT/kernel_repo_commit.txt"

{
  # kernel header and preload (real data and golden; HBM placement per spec §4.3 item 3)
  make -C "$IMPL" SH_DIR="$SH" arch="$ARCH" "$KERNEL=$CFG" "$KERNEL-clean" "$KERNEL-cfg" "$KERNEL-pld"
  # kernel software against the patched tree's runtime (the arch header was generated by build_arch.sh)
  make -C "$SH" sw cfg="$ARCH" app="$IMPL/sw/$APP"
} > "$OUT/build.log" 2>&1 || { echo "build failed, see $OUT/build.log" >&2; exit 1; }
cp "$IMPL/sw/$APP/preload.elf" "$IMPL"/sw/"$APP"/include/*.h "$OUT/"

PLD=$OUT/preload.elf
cd "$SH"
# Measurement run: gvsoc directly, no trace flags (`make run` adds --trace=/chip/cluster_0/redmule, and any trace
# flag switches gapy to the debug build, which is slower); stdin from /dev/null.
timeout "$SHVLA_SIM_TIMEOUT" ./install/bin/gvsoc --target=pulp.chips.flex_cluster.flex_cluster \
  --binary sw_build/softhier.elf run --preload "$PLD" < /dev/null > "$OUT/run.log" 2>&1 \
  || { echo "run failed or timed out, see $OUT/run.log" >&2; exit 1; }
if [ $TRACE = 1 ]; then
  timeout "$SHVLA_SIM_TIMEOUT" make runv pld="$PLD" > "$OUT/runv.log" 2>&1
  make pfto > "$OUT/pfto.log" 2>&1
  cp sw_build/perfetto.json "$OUT/perfetto.json"
fi
if [ $HBM = 1 ]; then
  timeout "$SHVLA_SIM_TIMEOUT" ./install/bin/gvsoc --target=pulp.chips.flex_cluster.flex_cluster \
    --binary sw_build/softhier.elf run --preload "$PLD" --trace=hbm_ctrl 2>&1 | gzip > "$OUT/hbm_ctrl.log.gz"
  zcat "$OUT/hbm_ctrl.log.gz" | python3 "$HERE/hbm_channel_count.py" "$ARCH" > "$OUT/hbm_channels.txt"
  tail -1 "$OUT/hbm_channels.txt" | sed 's/^/  /'
fi
grep -h "Performance Counter" "$OUT/run.log" | sed 's/^/  /'
grep -h "\[check\]" "$OUT/run.log" | awk '{bad+=$7; if ($11+0>m) m=$11+0} END {printf "  check: %d clusters, bad %d, max_ulp %d\n", NR, bad, m}'
