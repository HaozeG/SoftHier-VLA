#!/usr/bin/env python3
"""List every H1 run whose output check failed, for fixing later: docs/analysis/wrong-output-runs-h1.md.

    python3 infra/kernel-runs/wrong_runs.py

Reads every result CSV in results/ (GEMM sweeps, upstream settings, transposed GEMM, FlatAttention, row kernels).
For SummaGEMM splitK it also tests the working rule from the M = 50 sweep (2026-11-20): splitK is correct only when
the groups fill the whole mesh (64 active clusters) and each group takes at most 2 N steps (N_iter <= 2). The page
says which wrong runs the rule explains and whether any checked run contradicts it. Wrong runs are never picks
(final_runs.py and the explorer take checked runs only); this list is the to-do for the kernel fixes.
"""
import csv
from pathlib import Path

HERE = Path(__file__).resolve().parent
RES = HERE / "results"
OUT = HERE.parents[1] / "docs" / "analysis" / "wrong-output-runs-h1.md"
MESH = 64


def rows(name):
    p = RES / name
    return list(csv.DictReader(p.open())) if p.exists() else []


def gemm_info(r, src):
    sx = int(r.get("scale_x") or r.get("scale")); sy = int(r.get("scale_y") or r.get("scale"))
    g, st = int(r["groups"]), r["strategy"]
    Np, nt = int(r["n_size"]), int(r["n_tile"])
    n_iter = -(-(Np // g) // (sx * nt)) if st == "splitN" else -(-Np // (sx * nt))
    shape = r.get("orig_shape") or r["shape"]
    M, N, _ = (int(x) for x in r["shape"].split("x"))
    return dict(src=src, shape=shape, cand=r["cand"], strategy=st, group=f"{sx}x{sy}", groups=g, active=g * sx * sy,
                n_iter=n_iter, tile=f"{r['m_tile']}x{r['n_tile']}x{r['k_tile']}",
                pad=f"{r['m_size']}x{r['n_size']}x{r['k_size']}", time=r.get("time_ns") or "",
                bad=int(r["bad"] or 0), out=M * N, max_ulp=r.get("max_ulp", ""), status=r["status"],
                run_dir=r.get("run_dir", ""))


def main():
    g = []
    for name, src in (("gemm_sweep_h1.csv", "gemm_sweep"), ("gemm_smallm_h1.csv", "gemm_smallm_sweep"),
                      ("gemm_upstream_h1.csv", "gemm_upstream"), ("gemm_transpose_h1.csv", "gemm_transpose")):
        g += [gemm_info(r, src) for r in rows(name) if r["status"] in ("ok", "wrong")]
    wrong = [x for x in g if x["status"] == "wrong"]
    sk = [x for x in g if x["strategy"] == "splitK"]
    rule = lambda x: x["active"] == MESH and x["n_iter"] <= 2            # noqa: E731  (predicts "correct")
    explained = [x for x in wrong if x["strategy"] == "splitK" and not rule(x)]
    unexplained = [x for x in wrong if x not in explained]
    contra = [x for x in sk if x["status"] == "ok" and not rule(x)]
    attn = [r for r in rows("attn_sweep_h1.csv") if r["status"] == "wrong"]
    other = [(n, r) for n in ("row_kernels_h1.csv", "eltwise_pipeline_h1.csv")
             for r in rows(n) if r["status"] not in ("ok",)]

    L = ["<!-- generated by `python3 infra/kernel-runs/wrong_runs.py`; do not edit by hand -->",
         "# H1 runs with wrong output (to fix)", "",
         "Every run on arch H1 whose output check failed, from the result CSVs in `infra/kernel-runs/results/`. Wrong "
         "runs are never picks: `final_runs.py`, `to_constants.py` and the kernel explorer use checked runs only. "
         "This page is the to-do list for the kernel fixes.", "",
         "## Summary", "",
         "| kernel | runs checked | wrong |", "| --- | ---: | ---: |"]
    for k, xs in (("SummaGEMM splitK", sk), ("SummaGEMM splitN / Nosplit", [x for x in g if x["strategy"] != "splitK"])):
        L.append(f"| {k} | {len(xs)} | {sum(x['status'] == 'wrong' for x in xs)} |")
    na = len(rows("attn_sweep_h1.csv"))
    L.append(f"| FlatAttention | {na} | {len(attn)} |")
    L.append(f"| row kernels (Eltwise, Activation, LayerNorm, RMSNorm) | "
             f"{len(rows('row_kernels_h1.csv')) + len(rows('eltwise_pipeline_h1.csv'))} | {len(other)} |")
    L += ["", "## SummaGEMM splitK", "",
          "Working rule (M = 50 sweep, 2026-11-20; cause not verified in code): splitK is correct only when the "
          "groups fill the whole mesh **and** each group takes at most two N steps,", "",
          "$$\\text{correct} \\iff g \\cdot s_x \\cdot s_y = 64 \\;\\wedge\\; N_{iter} = \\lceil N_{pad} / (s_x \\cdot "
          "n_{tile}) \\rceil \\le 2 .$$", "",
          f"* wrong splitK runs the rule explains: **{len(explained)} of "
          f"{sum(x['strategy'] == 'splitK' for x in wrong)}**",
          f"* checked splitK runs that contradict it (rule says wrong, output passed): **{len(contra)}**"
          + (": " + ", ".join(f"`{x['shape']} {x['cand']}`" for x in contra) if contra else ""),
          f"* wrong runs it does not explain: **{len(unexplained)}**"
          + (": " + ", ".join(f"`{x['shape']} {x['cand']}`" for x in unexplained) if unexplained else ""), "",
          "Suspected causes, to check in `SummaGEMM.h` when fixing:", "",
          "1. **N_iter >= 3**: only group 0 (`store_active`) stores and clears its Z buffer after the reduction; the "
          "other groups never clear their two Z buffers, so the third N step adds onto stale partial sums.",
          "2. **fewer than 64 active clusters**: the FlooNoC group reduction mask spans the whole mesh and takes in "
          "clusters outside the groups (nearly every element wrong).", "",
          "| shape | candidate | source | group | groups | active | N_iter | tile | padded | bad / outputs | max ULP | cause |",
          "| --- | --- | --- | --- | ---: | ---: | ---: | --- | --- | ---: | ---: | --- |"]
    for x in sorted([x for x in wrong if x["strategy"] == "splitK"],
                    key=lambda x: ([int(v) for v in x["shape"].split("x")], x["cand"])):
        cause = " + ".join(c for c, f in (("active < 64", x["active"] < MESH), ("N_iter >= 3", x["n_iter"] >= 3)) if f) \
            or "not explained"
        L.append(f"| `{x['shape']}` | `{x['cand']}` | {x['src']} | {x['group']} | {x['groups']} | {x['active']} | "
                 f"{x['n_iter']} | {x['tile']} | {x['pad']} | {x['bad']:,} / {x['out']:,} | {x['max_ulp']} | {cause} |")
    ns = [x for x in wrong if x["strategy"] != "splitK"]
    if ns:
        L += ["", "## SummaGEMM splitN / Nosplit", "", "| shape | candidate | source | bad / outputs | run folder |",
              "| --- | --- | --- | ---: | --- |"]
        L += [f"| `{x['shape']}` | `{x['cand']}` | {x['src']} | {x['bad']:,} / {x['out']:,} | `{x['run_dir']}` |" for x in ns]
    L += ["", "## FlatAttention", ""]
    if attn:
        L += ["| shape | candidate | mode | groups (sx x sy) | block Br x Bc | bad | max ULP | run folder |",
              "| --- | --- | --- | --- | --- | ---: | ---: | --- |"]
        L += [f"| `{r['shape']}` | `{r['cand']}` | {'async' if r['async'] == '1' else 'collective'} | {r['sx']}x{r['sy']} | "
              f"{r['Br']}x{r['Bc']} | {int(r['bad']):,} | {r['max_ulp']} | `{r['run_dir']}` |" for r in attn]
        L += ["", "Output checked against a float64 golden of the padded, unmasked computation (abs tolerance 0.02). "
              "Not investigated yet."]
    else:
        L.append("None.")
    L += ["", "## Row kernels", "", "None." if not other else
          "\n".join(f"* `{r.get('name')}` ({n}): {r['status']}" for n, r in other)]
    L += ["", "## Run folders (splitK)", "", "Each folder has `kernel_cfg.py`, `build.log` and `run.log` (the `[check]` "
          "lines give the per-cluster bad counts).", ""]
    L += [f"* `{x['shape']} {x['cand']}`: `{x['run_dir']}`" for x in wrong if x["strategy"] == "splitK"]
    OUT.write_text("\n".join(L) + "\n")
    print(f"{OUT}: {len(wrong)} GEMM wrong ({len(explained)} explained by the splitK rule, {len(contra)} contradictions, "
          f"{len(unexplained)} unexplained), {len(attn)} FlatAttention wrong, {len(other)} row-kernel failures")


if __name__ == "__main__":
    main()
