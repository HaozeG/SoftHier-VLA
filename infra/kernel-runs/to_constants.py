#!/usr/bin/env python3
"""Write the `h1_kernels` section of infra/workload-modeling/constants.yaml from the H1 results.

    to_constants.py            # rewrite the section between the BEGIN/END markers in place
    to_constants.py --print    # print it only

One entry per constants key the stage-1 model needs for W1 and W1-b (smolvla_ops.hand_kernel_key with group
h1_kernels, lowerings STAGE1_LOWERING and STAGE1_LOWERING_W1B). Values: results/final_h1.csv (the picked setting
of every GEMM shape and row kernel, re-run on the frozen build) and results/attn_sweep_h1.csv (FlatAttention, run
on the frozen build). Provenance per stage-1 spec §4.3 item 7: kernel repo commit plus build hash, simulator tree
and patch-series hash (sim_stamp.json of the run), kernel parameters; sweep size and range; trace folder.
"""
import csv
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
CONST = REPO / "infra/workload-modeling/constants.yaml"
sys.path.insert(0, str(REPO / "infra/workload-modeling"))
from workload_modeling import constants as cst, smolvla_ops as m  # noqa: E402

BEGIN = "# BEGIN h1_kernels (generated by infra/kernel-runs/to_constants.py; do not edit by hand)"
END = "# END h1_kernels"
KREPO_COMMIT = "HaozeG/gvsoc@aa57690 (branch gelu-layernorm-kernels; = dc749bc"  # commit of the frozen build
BUILD2 = "de53537"   # final_runs.BUILD2: aa57690 + the optional GEMM_CHECK_ABS_TOL check (gemm_smallm_sweep.py picks)
KREPO_COMMIT2 = ("HaozeG/gvsoc@de53537 (branch gelu-layernorm-kernels; aa57690 + optional GEMM_CHECK_ABS_TOL check, "
                 "same binary without it")


def rd(p):
    return list(csv.DictReader(open(HERE / "results" / p)))


def stamp(run_dir):
    s = json.load(open(Path(run_dir) / "sim_stamp.json"))["gvsoc_series"]
    return f"GVSoC tree {s['tree'][:7]} (patch series sha256 {s['series_sha256'][:8]})"


def trace_of(prefix):
    for r in rd("traces_h1.csv"):
        if r["name"].startswith(prefix) and r["status"] == "ok":
            return f"trace {r['dir'].replace(str(Path.home()), '~')}/perfetto.json"
    return None


def main():
    c = cst.load()
    need = {}
    for tag, low in (("W1", m.STAGE1_LOWERING), ("W1-b", m.STAGE1_LOWERING_W1B)):
        for r in m.build(c, "vlabench-3cam", low):
            k = m.hand_kernel_key(r, "h1_kernels")
            if k:
                need.setdefault(k, {"tags": set(), "ops": set()})
                need[k]["tags"].add(tag)
                need[k]["ops"].add(r.op)
    final = {r["name"]: r for r in rd("final_h1.csv")}
    gsweep, asweep = rd("gemm_sweep_h1.csv"), rd("attn_sweep_h1.csv")
    ssweep = rd("gemm_smallm_h1.csv") if (HERE / "results/gemm_smallm_h1.csv").exists() else []
    # upstream's own settings (gemm_upstream.py: soft_hier_je opt() ported), candidates like the sweeps'
    usweep = [r for r in (rd("gemm_upstream_h1.csv") if (HERE / "results/gemm_upstream_h1.csv").exists() else [])
              if r["status"] != "skipped_m_iter"]
    # transposed GEMM runs (gemm_transpose.py): candidates of the operator's shape, setting "T:<candidate>"
    tsweep = [dict(r, shape=r["orig_shape"], run_shape=r["shape"], cand="T:" + r["cand"])
              for r in (rd("gemm_transpose_h1.csv") if (HERE / "results/gemm_transpose_h1.csv").exists() else [])]
    build = next(iter(final.values()))["build"]
    out = {}
    for key in sorted(need, key=lambda k: (m.STAGES.index(k.split(".")[1]), k)):
        _, stage, name = key.split(".")
        kern, shape = name.rsplit("_", 1)
        wl = " and ".join(sorted(need[key]["tags"]))
        ops = ", ".join(sorted(need[key]["ops"]))
        if kern == "flatattention":
            ok = [r for r in asweep if r["shape"] == shape and r["status"] == "ok"]
            b = min(ok, key=lambda r: int(r["time_ns"]))
            t, run_dir = int(b["time_ns"]), b["run_dir"]
            n_all = sum(1 for r in asweep if r["shape"] == shape)
            ts = sorted(int(r["time_ns"]) for r in ok)
            params = (f"attn {'async' if b['async'] == '1' else 'collective'} flatten_scale {b['sx']}x{b['sy']} "
                      f"block {b['Br']}x{b['Bc']} q_pad {b['q_pad']} kv_pad {b['kv_pad']}")
            note = (f"fastest of {len(ok)} checked settings ({ts[0]:,} to {ts[-1]:,} ns; {n_all - len(ok)} failed the "
                    f"check); padded, unmasked, GQA folds query heads (work {b['work_ratio']}x nominal); output within "
                    f"0.02 of a float64 golden (max {b['max_ulp']} ULP)")
            tr_prefix = f"{shape}_{b['cand']}"
        else:
            fname = f"gemm_{shape}" if kern == "gemm" else name
            if kern == "eltwise_pixel_shuffle":
                fname = name
            f = final[fname]
            t, run_dir = int(f["time_ns"]), f["dir"]
            if kern == "gemm":
                ok = [r for r in gsweep + ssweep + usweep + tsweep if r["shape"] == shape and r["status"] == "ok"]
                p = next(r for r in ok if r["cand"] == f["setting"])
                ts = sorted(int(r["time_ns"]) for r in ok)
                if "scale_x" in p and p.get("scale_x"):
                    group = f"group {p['scale_x']}x{p['scale_y']} (x by y)"
                else:
                    group = f"scale {p['scale']}"
                params = (f"gemm {p['strategy']} tile {p['m_tile']}/{p['n_tile']}/{p['k_tile']} {group} "
                          f"groups {p['groups']} padded {p['m_size']}x{p['n_size']}x{p['k_size']}")
                if p["cand"].startswith("T:"):
                    params = f"gemm transposed (Z^T = W^T X^T, run as {p['run_shape']}): " + params[5:]
                check = ("within 0.02 (absolute) of the replay golden (splitK: NoC reduction order differs)"
                         if p["strategy"] == "splitK" else "bit-exact against the replay golden")
                note = (f"fastest of {len(ok)} checked settings in the sweeps ({ts[0]:,} to {ts[-1]:,} ns, mixed builds; "
                        f"re-run on the recorded build: {t:,} ns); work {p['work_ratio']}x nominal; {check}")
                if any(r is p for r in usweep):
                    note += "; upstream's own setting (soft_hier_je gemm_auto.py opt(), gemm_upstream.py)"
                if p["cand"].startswith("T:"):
                    note += ("; transposed: W^T is laid out offline, X^T and Z^T are activation layouts the "
                             "neighbouring operators must produce and accept (that cost is not in this time)")
                tr_prefix = f"{shape}_{f['setting']}"
            else:
                params = f"{f['kernel']} {f['setting']}"
                note = ("pipelined row schedule (ELT_PIPELINE: store row j-1 and load row j+1 while Spatz computes "
                        "row j); " if f["setting"].endswith("pipeline=1") else "")
                note += "one run, exact shape; output check passed" + (
                    " (32 ULP against float64 x / rms(x); the kernel has no weight and no eps)" if kern == "rmsnorm"
                    else " (bit-exact against the replay golden)")
                tr_prefix = name
        tr = trace_of(tr_prefix)
        note += f"; {tr}" if tr else "; no trace recorded (stage1-spec §4.3 item 9)"
        note += f"; {wl}: {ops}"
        b = final[fname]["build"] if kern not in ("flatattention",) else build
        if b == BUILD2:
            krepo = f"{KREPO_COMMIT2})"
        elif len(b) == 7:                         # re-run on a kernel commit (final_runs.py: kernel_repo_commit.txt)
            krepo = f"HaozeG/gvsoc@{b} (submodule third_party/softhier-kernels)"
        else:                                     # the frozen stage-1 build (hash of its worktree diff)
            krepo = f"{KREPO_COMMIT} + build {b[:8]})"
        src = f"{krepo}; {stamp(run_dir)}; arch_h1.py; {params}"
        out[key] = (t, src, note)
    lines = [BEGIN,
             "# Kernel times on H1, ns per call, one operator instance per run: the W1 preset, the fastest checked run",
             "# per kernel over every result set (stage-1 sweeps, docs/designs/stage1-spec.md §4, and later runs: transposed",
             "# GEMM, pipelined Eltwise). The stage-1 picks: results/final_h1_stage1.csv.",
             "# Run folders: ~/.cache/softhier-vla/stage1-h1/ (final/, attn/); driver scripts: infra/kernel-runs/.",
             "h1_kernels:"]
    stage = None
    for key, (t, src, note) in out.items():
        _, st, name = key.split(".")
        if st != stage:
            lines.append(f"  {st}:")
            stage = st
        lines.append(f"    {name}:")
        lines.append(f"      {{value: {t}, unit: ns, label: measured, workload: vlabench-3cam, arch: h1, "
                     f"source: {json.dumps(src, ensure_ascii=False)}, note: {json.dumps(note, ensure_ascii=False)}}}")
    lines.append(END)
    block = "\n".join(lines) + "\n"
    groups = [(g, *plan_block(g)) for g in PLAN_GROUPS if (HERE / "results" / PLAN_GROUPS[g][0]).exists()]
    if "--print" in sys.argv:
        print(block)
        for _, pblock, _ in groups:
            print(pblock)
        return
    s = CONST.read_text()
    blocks = [(BEGIN, END, block)] + [(f"# BEGIN {g} ({GEN})", f"# END {g}", b) for g, b, _ in groups]
    for b0, e0, blk in blocks:
        if b0 in s:
            s = re.sub(re.escape(b0) + r".*?" + re.escape(e0) + r"\n", lambda _: blk, s, flags=re.S)
        else:
            s = s.rstrip("\n") + "\n\n" + blk
    CONST.write_text(s)
    print(f"wrote {len(out)} h1_kernels entries and " + ", ".join(f"{n} {g}" for g, _, n in groups)
          + f" to {CONST.relative_to(REPO)}")


GEN = "generated by infra/kernel-runs/to_constants.py; do not edit by hand"
# group: (pick file, page, selection). Every number in these groups comes from runs under the deployment plan.
PLAN_GROUPS = {
    "h1_plan": ("plan_pick_h1.csv", "W1", "upstream"),
    "h1_plan_w1b": ("plan_pick_w1b_h1.csv", "W1-b", "upstream"),
    "h1_psweep": ("plan_sweep_pick_w1_h1.csv", "W1", "constrained"),
    "h1_psweep_w1b": ("plan_sweep_pick_w1b_h1.csv", "W1-b", "constrained"),
}
HEAD = {
    "upstream": ["# Kernel times on H1, ns per call, {page} under the stage-1 baseline: upstream's whole-graph HBM plan and",
                 "# kernel-selection rule (decision 2026-11-25; workload_modeling/deploy_plan.py, upstream_rules.py). One entry",
                 "# per run key of the plan (<kernel>_<shape>[_zto|_xfrom][_p<placement overrides>]); value = the fastest run whose",
                 "# output check passed among upstream's candidates and the recorded fixes (plan_runs.py pick --page {page}).",
                 "# Every run: results/plan_runs_h1.csv; run folders: ~/.cache/softhier-vla/stage1-h1/plan/."],
    "constrained": ["# Kernel times on H1, ns per call, {page} under the same deployment plan with the free knobs searched",
                    "# (plan-constrained sweep, plan_sweep.py): placement, head-major reshapes and head padding as the plan",
                    "# carries them; attention settings (and with them the head padding) chosen for the whole graph, GEMM",
                    "# tiles / groups / strategy, Eltwise schedule. Value = the run of the selected combination's variant",
                    "# (plan_sweep.py pick --page {page}). Every run: results/plan_sweep_h1.csv and plan_runs_h1.csv; run folders:",
                    "# ~/.cache/softhier-vla/stage1-h1/plan_sweep/ and plan/."],
}


def krepo_of(run_dir):
    """Kernel repo commit of a run (kernel_repo_commit.txt: the commit, then the diff stat of the working tree)."""
    lines = (Path(run_dir) / "kernel_repo_commit.txt").read_text().split("\n")
    dirty = any(x.strip() for x in lines[1:])
    return f"HaozeG/gvsoc@{lines[0][:7]}" + (" + working-tree diff" if dirty else "") + \
        " (submodule third_party/softhier-kernels, branch upstream-deployment-plan)"


def plan_block(group):
    """One plan group: per run key of the deployment plan (deploy_plan.Plan), the selected run of the group's pick
    file (plan_runs.py pick: upstream's rule; plan_sweep.py pick: the plan-constrained sweep)."""
    fname, page, sel = PLAN_GROUPS[group]
    pick = rd(fname)
    runs = rd("plan_runs_h1.csv") + (rd("plan_sweep_h1.csv") if sel == "constrained" else [])
    lines = [f"# BEGIN {group} ({GEN})"] + [x.format(page=page) for x in HEAD[sel]] + [f"{group}:"]
    stage = None
    for p in sorted(pick, key=lambda r: m.STAGES.index(r["key"].split(".")[0])):
        st, name = p["key"].split(".", 1)
        mine = [r for r in runs if r["key"] == p["key"] and (sel == "upstream" or r.get("vid", p.get("vid")) == p["vid"])]
        ok = [r for r in mine if r["status"] == "ok"]
        failed = [r for r in mine if r["status"] != "ok"]
        src = f"{krepo_of(p['run_dir'])}; {stamp(p['run_dir'])}; arch_h1.py; {p['kernel']} {p['cand']}"
        note = (f"fastest of {len(ok)} checked plan run(s)" if len(ok) > 1 else "one checked plan run") + \
            f"; ops {p['ops'].replace(',', ', ')} (x{p['count']} per call)"
        if sel == "constrained":
            note += f"; run variant {p['vid'].split('@', 1)[1]} (padded sizes); candidate source {p['source']}"
        if p["fix"]:
            note += f"; recorded fix: {p['fix']}"
        if failed:
            note += "; failed the output check: " + ", ".join(f"{r['cand']} ({int(r['bad']):,} bad)" for r in failed
                                                              if r["bad"])
        note += "; no trace recorded"
        if st != stage:
            lines.append(f"  {st}:")
            stage = st
        lines.append(f"    {name}:")
        lines.append(f"      {{value: {int(p['time_ns'])}, unit: ns, label: measured, workload: vlabench-3cam, arch: h1, "
                     f"source: {json.dumps(src, ensure_ascii=False)}, note: {json.dumps(note, ensure_ascii=False)}}}")
    lines.append(f"# END {group}")
    return "\n".join(lines) + "\n", len(pick)


if __name__ == "__main__":
    main()
