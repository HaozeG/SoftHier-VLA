# ------------------------------------------------------------------------------------------- the join
class Explorer:
    def __init__(self, c=None):
        self.c = c or constants.load()
        self.G, self.S, self.A = _drivers()
        self.peak = self.c.peak_total(ARCH)
        self.peak_cl = self.c.peak_per_cluster(ARCH)
        self.rm_blk = redmule_blocks(self.c)
        self.rm_mac_per_ns = self.peak_cl / 2 / 1e9      # RedMulE MAC per ns per cluster (1,024 on H1)
        self.bw = self.c.value(f"arch.{ARCH}.hbm_channels") * self.c.value(f"arch.{ARCH}.hbm_bw_per_channel") * 1e9
        self.final = {r["name"]: r for r in _rows(RES / "final_h1.csv")}
        self.sq = _rows(RES / "gemm_sweep_h1.csv")
        self.sm = _rows(RES / "gemm_smallm_h1.csv")
        self.at = _rows(RES / "attn_sweep_h1.csv")
        # result sets measured after stage 1: transposed GEMM, pipelined Eltwise (candidates like the sweeps)
        self.tr = _rows(RES / "gemm_transpose_h1.csv") if (RES / "gemm_transpose_h1.csv").exists() else []
        self.elt = _rows(RES / "eltwise_pipeline_h1.csv") if (RES / "eltwise_pipeline_h1.csv").exists() else []
        self.rk = _rows(RES / "row_kernels_h1.csv")
        # upstream's own settings (soft_hier_je opt(), gemm_upstream.py / attn_sweep.upstream_cand): candidates too
        self.up = _rows(RES / "gemm_upstream_h1.csv") if (RES / "gemm_upstream_h1.csv").exists() else []
        # the stage-1 picks, frozen (reference only: constants.yaml now holds the W1 preset's fastest runs)
        f1 = RES / "final_h1_stage1.csv"
        self.final_s1 = {r["name"]: r for r in _rows(f1)} if f1.exists() else dict(self.final)
        self.traces = json.loads((RES / "trace_summary_h1.json").read_text())
        self.kernels: dict[str, dict] = {}
        self.checks: list[dict] = []
        self.pages = [self._page(*p) for p in PAGES]
        for k in self.kernels.values():
            self._finish_kernel(k)
        self._check_sums()

    # ----------------------------------------------------------------- operators -> kernels
    def _page(self, name: str, low, desc: str) -> dict:
        wid = self.c.primary_workload.id
        rows = m.annotate(m.build(self.c, wid, low or m.kernel_set(wid).lowering))
        inc: dict[tuple[str, str], list[m.OpRow]] = {}
        for r in rows:
            if (r.stage, r.op) in m.INCLUDED_IN:
                inc.setdefault((r.stage, m.INCLUDED_IN[(r.stage, r.op)]), []).append(r)
        ops = []
        for r in rows:
            key = m.hand_kernel_key(r)
            ns = m.hand_kernel_ns(self.c, wid, r)
            flop = r.flop + sum(x.flop for x in inc.get((r.stage, r.op), []))
            op = dict(stage=r.stage, op=r.op, cls=r.cls, layers=r.layers, shape=list(r.shape), count=r.count,
                      flop=flop, traffic=r.memory_traffic_bytes, weights=r.weights_read_bytes,
                      kernel_name=r.hand_kernel, kernel=None, ns=ns,
                      included_in=m.INCLUDED_IN.get((r.stage, r.op)), host=r.op in m.HOST_OPS)
            if key and ns is not None:
                kname = key.split(".", 2)[2]
                op["kernel"] = kname
                k = self.kernels.setdefault(kname, self._new_kernel(kname, r, ns, key))
                k["uses"].append(dict(page=name, stage=r.stage, op=r.op, count=r.count, layers=r.layers,
                                      total_ns=r.count * ns))
                k["flop_call"] = flop / r.count
                k["bytes_call"] = r.memory_traffic_bytes / r.count
                k["weights_call"] = r.weights_read_bytes / r.count
            ops.append(op)
        return dict(name=name, desc=desc, ops=ops, sums=render.kernel_sums(self.c, wid, rows))

    def _new_kernel(self, kname: str, r: m.OpRow, ns: float, key: str) -> dict:
        kind = "gemm" if r.cls == "gemm" else "attn" if r.cls == "attn" else "row"
        e = self.c.get(key)
        return dict(name=kname, kind=kind, kernel_label=r.hand_kernel, shape=list(r.shape), time_ns=ns,
                    constants_key=key, constants_source=e.source, constants_note=e.note or "", uses=[])

    # ----------------------------------------------------------------- per kernel: space, candidates, checks
    def _finish_kernel(self, k: dict) -> None:
        {"gemm": self._gemm, "attn": self._attn, "row": self._row}[k["kind"]](k)
        f = k["flop_call"]
        t = k["time_ns"] * 1e-9
        k["mfu"] = f / (t * self.peak)
        k["t_ideal_ns"] = f / self.peak * 1e9
        k["t_hbm_min_ns"] = k["bytes_call"] / self.bw * 1e9
        k["hbm_eff_bw"] = k["bytes_call"] / t
        k["roof_ns"] = max(k["t_ideal_ns"], k["t_hbm_min_ns"])
        k["bound"] = "compute" if k["t_ideal_ns"] >= k["t_hbm_min_ns"] else "HBM"
        if k["kind"] != "row":
            self._wrong_faster(k)
            s = k["selected"]["setting"]
            # f_pad = shape padding (whole tiles, work_ratio) x RedMulE array padding (whole 32 x 64 output blocks).
            # Both are work the mapping fixes before the kernel runs: zeros or empty block slots that cost full
            # array time. Array padding is modelled for GEMM only; FlatAttention's RedMulE call shapes are not read
            # yet, so attention keeps f_pad_array = 1 (its array padding, if any, stays in f_rest).
            k["f_pad_shape"] = 1.0 / k["selected"]["work_ratio"]
            k["f_pad_array"] = s.get("f_array", 1.0) if k["kind"] == "gemm" else 1.0
            k["f_pad"] = k["f_pad_shape"] * k["f_pad_array"]
            k["f_pad_text"] = f_pad_text(k)
            k["f_occ"] = s["active"] / NCL
            k["f_rest"] = k["mfu"] / (k["f_pad"] * k["f_occ"])

    def _trace(self, name: str) -> dict | None:
        t = self.traces.get(name)
        return dict(t, name=name) if t else None

    def _cand(self, r: dict, setting: dict, source: str, technique: str) -> dict:
        t = int(r["time_ns"]) if r.get("time_ns") else None
        # est_ns: the shared model (kernel_model) for GEMM settings, recomputed here rather than the CSV column
        # (older sweep rows carry the earlier rough model)
        est = setting.get("model_ns") if "model_ns" in setting else (int(r["est_ns"]) if r.get("est_ns") else None)
        return dict(cand=r["cand"], source=source, technique=technique, setting=setting,
                    work_ratio=float(r["work_ratio"]), time_ns=t, est_ns=est,
                    status=r["status"], bad=r.get("bad"), max_ulp=r.get("max_ulp"), run_dir=r.get("run_dir", ""),
                    upstream=source == "gemm_upstream", transposed=source == "gemm_transpose",
                    run_shape=r.get("shape"))

    def _gemm(self, k: dict) -> None:
        M, N, K = k["shape"]
        shp = f"{M}x{N}x{K}"
        cands = []
        for r in self.sq:
            if r["shape"] == shp:
                s = gemm_setting(r, self.rm_blk, self.rm_mac_per_ns)
                cands.append(self._cand(r, s, "gemm_sweep", gemm_technique(s)))
        for r in self.sm:
            if r["shape"] == shp:
                s = gemm_setting(r, self.rm_blk, self.rm_mac_per_ns)
                cands.append(self._cand(r, s, "gemm_smallm_sweep", gemm_technique(s)))
        seen = {r.get("run_dir") for r in self.sq if r["shape"] == shp}
        for r in self.up:            # upstream settings identical to a gemm_sweep run reuse it: listed once
            if r["shape"] == shp and r["status"] != "skipped_m_iter" and r.get("run_dir") not in seen:
                s = gemm_setting(r, self.rm_blk, self.rm_mac_per_ns)
                cands.append(self._cand(r, s, "gemm_upstream", gemm_technique(s)))
        space = space_counts(gemm_square_space(self.G, M, N, K), True)
        if (M, N, K) in self.S.SHAPES:
            for t, n in space_counts(self.S.enumerate_all(M, N, K), False).items():
                space[t] = space.get(t, 0) + n
        # transposed runs (gemm_transpose.py): Z^T = W^T X^T as the GEMM N x M x K, candidates of this operator
        # like any other mapping; named "T:<setting>". Not in constants.yaml, so not part of the stage-1 pick.
        trs = [r for r in self.tr if r["orig_shape"] == shp]
        for r in trs:
            s = gemm_setting(r, self.rm_blk, self.rm_mac_per_ns)
            cands.append(dict(self._cand(r, s, "gemm_transpose", gemm_technique(s)), cand="T:" + r["cand"]))
        if trs:
            for t, n in space_counts(gemm_square_space(self.G, N, M, K), True).items():
                space[t] = space.get(t, 0) + n
        fin = self.final[k["name"]]
        ok = [c for c in cands if c["status"] == "ok"]
        best = min(ok, key=lambda c: c["time_ns"])
        sel = next(c for c in cands if c["cand"] == fin["setting"])
        sel = dict(sel, time_final_ns=int(fin["time_ns"]))
        self._check("pick", k["name"], best["cand"] == fin["setting"],
                    f"fastest checked of {len(ok)} = {best['cand']} ({best['time_ns']:,} ns); "
                    f"final_h1 = {fin['setting']}")
        self._check("constants", k["name"], int(fin["time_ns"]) == int(k["time_ns"]),
                    f"final_h1 {int(fin['time_ns']):,} ns, constants {int(k['time_ns']):,} ns")
        k.update(candidates=cands, selected=sel, space=space,
                 techniques=self._tech_table(GEMM_TECHNIQUES, space, cands, sel, (M, N, K) in self.S.SHAPES),
                 not_swept=gemm_not_swept(k["shape"], cands))
        self._traces_for(k, shp, cands, sel)
        self._stage1(k)

    def _stage1(self, k: dict) -> None:
        """The stage-1 pick of this kernel (final_h1_stage1.csv), when the selected run differs from it."""
        f1 = self.final_s1.get(k["name"])
        k["stage1"] = None
        if f1 and (f1["setting"] != self.final[k["name"]]["setting"] or f1["build"] != self.final[k["name"]]["build"]):
            k["stage1"] = dict(setting=f1["setting"], time_ns=int(f1["time_ns"]),
                               speedup=int(f1["time_ns"]) / k["time_ns"])

    def _attn(self, k: dict) -> None:
        h, sq, skv, d = k["shape"]
        name = f"{h}x{sq}x{skv}x{d}"
        hq, hkv = self.A.SHAPES[name][0], self.A.SHAPES[name][1]
        cands = []
        up = self.A.upstream_cand(name)["cand"]
        for r in self.at:
            if r["shape"] == name:
                s = attn_setting(r, hq, hkv)
                cands.append(dict(self._cand(r, s, "attn_sweep", s["mode"]), upstream=r["cand"] == up))
        space: dict[str, int] = {}
        for c in self.A.candidates(name):
            t = "async" if c["async_"] else "collective"
            space[t] = space.get(t, 0) + 1
        ok = [c for c in cands if c["status"] == "ok"]
        best = min(ok, key=lambda c: c["time_ns"])
        self._check("pick", k["name"], best["time_ns"] == int(k["time_ns"]),
                    f"fastest checked of {len(ok)} = {best['cand']} ({best['time_ns']:,} ns); "
                    f"constants {int(k['time_ns']):,} ns")
        sel = dict(best, time_final_ns=best["time_ns"])
        k["stage1"] = None
        k.update(candidates=cands, selected=sel, space=space, hq=hq, hkv=hkv,
                 techniques=self._tech_table(ATTN_TECHNIQUES, space, cands, sel, True), not_swept=[])
        self._traces_for(k, name, cands, sel)

    def _row_not_swept(self, k: dict, fin: dict) -> list[dict]:
        """Activation's bias_enable (Activation.h: the bias added in the same pass) is never run: the bias before
        GELU is a separate Eltwise call."""
        if not k["name"].startswith("gelu_"):
            return []
        shp = k["name"].split("_", 1)[1]
        b = self.final.get(f"eltwise_bias_{shp}")
        return [dict(name="bias fused into the activation (bias_enable)", why=(
            "in Activation.h and acti_preload.py, never run on H1: the bias before GELU runs as its own Eltwise call"
            + (f" (eltwise_bias_{shp}, {int(b['time_ns']) / 1e3:.1f} µs)" if b else "")))]

    def _row(self, k: dict) -> None:
        fin = self.final[k["name"]]
        self._check("constants", k["name"], int(fin["time_ns"]) == int(k["time_ns"]),
                    f"final_h1 {int(fin['time_ns']):,} ns, constants {int(k['time_ns']):,} ns")
        tr = self._trace(k["name"])
        pipelined = fin["setting"].endswith(" pipeline=1")
        k.update(candidates=[], selected=dict(cand=fin["setting"], time_ns=int(fin["time_ns"]),
                                              run_dir=fin["dir"], setting=None),
                 space={}, techniques=[], not_swept=self._row_not_swept(k, fin), config=fin["setting"],
                 pipelined=pipelined)
        # runs of this kernel: the stage-1 schedule (row_kernels.py) and, for Eltwise, the pipelined schedule
        # (eltwise_pipeline.py; runs whose config sets pipeline); the pick is the fastest checked one
        runs = [(r["config"], int(r["time_ns"])) for r in self.rk if r["name"] == k["name"] and r["status"] == "ok"]
        for r in self.elt:
            cfg = Path(r["run_dir"]) / "kernel_cfg.py"
            if r["name"] == k["name"] and r["status"] == "ok" and cfg.exists() and "self.pipeline" in cfg.read_text():
                runs.append((runs[0][0] + " pipeline=1" if runs else "pipeline=1", int(r["time_ns"])))
        if runs:
            b = min(runs, key=lambda x: x[1])
            self._check("pick", k["name"], b[0] == fin["setting"],
                        f"fastest checked of {len(runs)} runs = {b[0]} ({b[1]:,} ns); final_h1 = {fin['setting']}")
        k["row_runs"] = [dict(setting=a, time_ns=t) for a, t in runs]
        self._stage1(k)
        rows = k["shape"][0]
        k["trace_status"] = "selected" if tr and tr.get("busy_frac") else "none"
        k["trace"] = tr
        k["trace_note"] = ("trace of this run" if k["trace_status"] == "selected" else "no trace")
        if pipelined and tr:                          # the traces are of the stage-1 runs
            k["trace_status"], k["trace_note"] = "other", "trace of the stage-1 schedule; the pipelined run is not traced"
        k["row_note"] = ("no mapping knob: the kernel spreads the rows over the clusters itself; the busy clusters "
                         "shown are read from the trace")
        if tr and tr.get("busy_frac"):
            k["active_trace"] = len(tr["active_clusters"])
            k["rows_per_cluster"] = -(-rows // NCL)
    def _tech_table(self, techs, space, cands, sel, enumerated: bool) -> list[dict]:
        out = []
        for t, desc, driver in techs:
            cs = [c for c in cands if c["technique"] == t]
            ok = [c for c in cs if c["status"] == "ok"]
            n_space = space.get(t, 0)
            out.append(dict(technique=t, desc=desc, driver=driver, valid=n_space,
                            enumerated=enumerated or driver == "gemm_sweep.py",
                            swept=len(cs), ok=len(ok), wrong=sum(c["status"] == "wrong" for c in cs),
                            failed=sum(c["status"] not in ("ok", "wrong") for c in cs),
                            best_ns=min((c["time_ns"] for c in ok), default=None),
                            best_cand=min(ok, key=lambda c: c["time_ns"])["cand"] if ok else None,
                            selected=sel["technique"] == t))
        return out

    def _traces_for(self, k: dict, prefix: str, cands: list[dict], sel: dict) -> None:
        """Trace status of the selected setting, and the placement-vs-trace check on every traced candidate."""
        by = {c["cand"]: c for c in cands}
        traced = []
        for name, t in sorted(self.traces.items()):
            if not name.startswith(prefix + "_"):
                continue
            cand = name[len(prefix) + 1:]
            traced.append(dict(t, name=name, cand=cand))
            c = by.get(cand)
            if c is not None and t.get("busy_frac"):
                c["trace"] = name
                s = c["setting"]
                if k["kind"] == "gemm":
                    pl = placement(s["sx"], s["sy"], s["groups"])
                else:
                    pl = placement(s["sx"], s["sy"], s["active_groups"])
                want = sorted(i for i, p in enumerate(pl) if p["g"] >= 0)
                unit = "redmule"
                got = t["active_by_unit"][unit]
                self._check("placement", f"{k['name']} / {cand}", want == got,
                            f"{len(want)} clusters from the kernel's group placement, {len(got)} with {unit} "
                            f"activity in the trace" + ("" if want == got else f"; differ at "
                                                        f"{sorted(set(want) ^ set(got))}"))
        k["traces"] = traced
        mine = next((t for t in traced if t["cand"] == sel["cand"]), None)
        if mine and mine.get("busy_frac"):
            k["trace_status"], k["trace"] = "selected", mine
            k["trace_note"] = "trace of the selected setting"
        else:
            other = [t for t in traced if t.get("busy_frac")]
            k["trace"] = other[0] if other else None
            if mine:
                why = "tracing the selected setting failed or timed out"
            elif sel["source"] == "gemm_smallm_sweep":
                why = ("the selected setting was never traced: trace_picks.py traces the gemm_sweep pick, "
                       "not the gemm_smallm_sweep one")
            else:
                why = "the selected setting was never traced"
            k["trace_status"] = "other" if other else "none"
            k["trace_note"] = why + (f"; the trace shown is of a non-selected candidate, {other[0]['cand']} "
                                     f"({other[0]['measured_ns']:,} ns vs {sel['time_ns']:,} ns selected)"
                                     if other else "")

    def _wrong_faster(self, k: dict) -> None:
        """Runs that failed the output check but were faster than the pick: their failure needs a look first."""
        sel = k["selected"]["time_ns"]
        k["wrong_faster"] = [dict(cand=c["cand"], time_ns=c["time_ns"], bad=c["bad"], max_ulp=c["max_ulp"])
                             for c in k["candidates"] if c["status"] == "wrong" and c["time_ns"] and c["time_ns"] < sel]

    def _check(self, kind: str, what: str, ok: bool, detail: str) -> None:
        self.checks.append(dict(kind=kind, what=what, ok=bool(ok), detail=detail))

    def _check_sums(self) -> None:
        for p in self.pages:
            tot = sum(o["count"] * o["ns"] for o in p["ops"] if o["ns"] is not None) / 1e6
            want = float(p["sums"]["total_ms"].replace(",", ""))
            self._check("sum", p["name"], abs(tot - want) < 0.006,
                        f"sum over operators of count x kernel time = {tot:.3f} ms; operator-graph page {want:.2f} ms")

    # ----------------------------------------------------------------- time budget (estimate)
    def budget(self, page: dict) -> list[dict]:
        """Per stage: ideal compute, padding, idle clusters, HBM floor, rest of the matrix kernels' time, row operators."""
        out = []
        for st in m.STAGES:
            b = dict(stage=st, ideal=0.0, padding=0.0, idle=0.0, hbm=0.0, rest=0.0, row=0.0)
            for o in page["ops"]:
                if o["stage"] != st or o["kernel"] is None:
                    continue
                k = self.kernels[o["kernel"]]
                n = o["count"]
                t = k["time_ns"]
                if k["kind"] == "row":
                    b["row"] += n * t
                    continue
                t0 = k["t_ideal_ns"]
                t1 = t0 / k["f_pad"]
                t2 = t1 / k["f_occ"]
                b["ideal"] += n * t0
                b["padding"] += n * (t1 - t0)
                b["idle"] += n * (t2 - t1)
                t3 = max(t2, k["t_hbm_min_ns"])      # HBM floor: unique bytes at the assumed bandwidth
                b["hbm"] += n * (t3 - t2)
                b["rest"] += n * (t - t3)
            out.append(b)
        return out

    # ----------------------------------------------------------------- stage-1 reference (estimate)
    def stage1_total(self, page: dict) -> float:
        """Call time in ms with the stage-1 picks instead of the selected kernels (kernel times add up as on the
        operator-graph page)."""
        t = 0.0
        for o in page["ops"]:
            if o["kernel"] is None or o["ns"] is None:
                continue
            s1 = self.kernels[o["kernel"]].get("stage1")
            t += o["count"] * (s1["time_ns"] if s1 else o["ns"])
        return t / 1e6

    # ----------------------------------------------------------------- page data for the HTML
    def data(self) -> dict:
        def mesh(k, s):
            if s is None:
                return None
            if k["kind"] == "gemm":
                return placement(s["sx"], s["sy"], s["groups"])
            return placement(s["sx"], s["sy"], s["active_groups"])
        kernels = {}
        for name, k in self.kernels.items():
            kk = {x: v for x, v in k.items()}
            for c in kk["candidates"]:
                c["mesh"] = mesh(k, c["setting"])
            if kk["kind"] != "row":
                kk["selected"] = dict(kk["selected"], mesh=mesh(k, kk["selected"]["setting"]))
            kernels[name] = kk
        return dict(
            arch=dict(peak=self.peak, peak_cluster=self.peak_cl, bw=self.bw, mesh=[MESH_X, MESH_Y], rm_blk=list(self.rm_blk)),
            pages=[dict(name=p["name"], desc=p["desc"], ops=p["ops"], budget=self.budget(p),
                        total_ms=p["sums"]["total_ms"], mfu=p["sums"]["total"]["mfu"],
                        stage1_ms=self.stage1_total(p)) for p in self.pages],
            kernels=kernels, checks=self.checks)


