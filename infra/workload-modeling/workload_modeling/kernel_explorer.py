# ------------------------------------------------------------------------------------------- spatial mapping
def placement(gx: int, gy: int, groups: int) -> list[dict]:
    """Group of each cluster, as grid_sync_group_init (flex_group_barrier.h:43) and SummaGEMM.h:131-138 place it.

    cluster id = x + 8 y (flex_runtime.h get_pos); groups tile the mesh in gx x gy blocks numbered row-major,
    group id = ceil(8 / gx) * (y / gy) + x / gx; a cluster works if its group id < groups."""
    nx = -(-MESH_X // gx)
    out = []
    for cid in range(NCL):
        x, y = cid % MESH_X, cid // MESH_X      # flex_runtime.h get_pos
        g = nx * (y // gy) + x // gx
        out.append({"g": g if g < groups else -1, "cx": x % gx, "cy": y % gy})
    return out


def _up(x: int, a: int) -> int:
    return -(-x // a) * a


def redmule_array_eff(m: int, n: int, k: int, blk: tuple[int, int, int]) -> float:
    """Share of the RedMulE array time that does real MACs for one call of an m x n output tile with reduction k.

    Z = X (m x k) . W (k x n) in GEMM naming; LightRedmule calls k its n and n its k. blk = redmule_blocks(); a
    partial block costs a full one. Shape padding (whole tiles) is counted in work_ratio, not here."""
    bm, bn, bk = blk
    return kernel_model.block_fill(m, n, k, kernel_model.Arch(1, 1, bm, bn, bk, 1, 1.0, 0.0, 0.0, 1.0))


def gemm_setting(r: dict, blk: tuple[int, int, int], mac_per_ns: float) -> dict:
    """Mapping parameters of a GEMM run row (gemm_sweep: square scale; gemm_smallm_sweep: scale_x, scale_y)."""
    sx = int(r.get("scale_x") or r.get("scale"))
    sy = int(r.get("scale_y") or r.get("scale"))
    g = int(r["groups"])
    mt, nt, kt = int(r["m_tile"]), int(r["n_tile"]), int(r["k_tile"])
    Mp, Np, Kp = int(r["m_size"]), int(r["n_size"]), int(r["k_size"])
    st = r["strategy"]
    m_it, n_it, k_it = kernel_model.iterations(Mp, Np, Kp, mt, nt, kt, sx, sy, g, st)   # SummaGEMM.h:142-144
    calls = m_it * n_it * k_it
    return dict(sx=sx, sy=sy, groups=g, strategy=st, mt=mt, nt=nt, kt=kt, Mp=Mp, Np=Np, Kp=Kp,
                active=g * sx * sy, m_iter=m_it, n_iter=n_it, k_iter=k_it, redmule_calls=calls,
                redmule_floor_ns=calls * mt * nt * kt / mac_per_ns,
                f_array=redmule_array_eff(mt, nt, kt, blk),
                tile_blk=[_up(mt, blk[0]), _up(nt, blk[1]), _up(kt, blk[2])],   # the tile as the array times it
                redmule_array_ns=calls * mt * nt * kt / redmule_array_eff(mt, nt, kt, blk) / mac_per_ns,
                square=sx == sy,
                model_ns=round(kernel_model.gemm_ns(Mp, Np, Kp, mt, nt, kt, sx, sy, g, st, KM_ARCH)["est_ns"]))


def f_pad_text(k: dict) -> str:
    """f_pad in words: where each part comes from, e.g.
    '0.75 = shape 1.00 (no padding) x block fill 0.75 (tile 128x96 runs as 128x128)'."""
    s = k["selected"]["setting"]
    if k["kind"] == "gemm":
        nom = "x".join(str(v) for v in k["shape"])
        pad = f"{s['Mp']}x{s['Np']}x{s['Kp']}"
        shape = "no padding" if k["f_pad_shape"] == 1.0 else f"{nom} padded to {pad}"
        t, tb = (s["mt"], s["nt"], s["kt"]), s["tile_blk"]
        if list(t) == tb:
            blocks = "tile fills whole blocks"
        elif t[2] == tb[2]:
            blocks = f"tile {t[0]}x{t[1]} runs as {tb[0]}x{tb[1]}"
        else:
            blocks = f"tile {t[0]}x{t[1]}x{t[2]} runs as {tb[0]}x{tb[1]}x{tb[2]}"
        return (f"{k['f_pad']:.2f} = shape {k['f_pad_shape']:.2f} ({shape}) x block fill "
                f"{k['f_pad_array']:.2f} ({blocks})")
    shape = "no padding" if k["f_pad_shape"] == 1.0 else f"q padded to {s['q_pad']}, kv to {s['kv_pad']}"
    return f"{k['f_pad']:.2f} = shape {k['f_pad_shape']:.2f} ({shape}) x block fill not modelled"


def gemm_technique(s: dict) -> str:
    if s["strategy"] == "Nosplit":
        return "Nosplit"
    return f"{s['strategy']}, {'square' if s['square'] else 'non-square'} groups"


def attn_setting(r: dict, hq: int, hkv: int) -> dict:
    sx, sy, Br, Bc = int(r["sx"]), int(r["sy"]), int(r["Br"]), int(r["Bc"])
    G = NCL // (sx * sy)
    qp, kvp = int(r["q_pad"]), int(r["kv_pad"])
    rows = qp * (hq // hkv)                   # GQA folds the query heads of one KV head into the rows
    return dict(sx=sx, sy=sy, Br=Br, Bc=Bc, groups=G, active_groups=min(G, hkv), heads_per_group=max(hkv // G, 1),
                active=min(G, hkv) * sx * sy, mode="async" if r["async"] == "1" else "collective",
                Br_s=Br // sy, Bc_s=Bc // sx, Tr=rows // Br, Tc=kvp // Bc, q_pad=qp, kv_pad=kvp)


# ------------------------------------------------------------------------------------------- mapping spaces
def gemm_square_space(G, M, N, K) -> list[dict]:
    """Every valid gemm_sweep.py candidate (its loop without the model ranking)."""
    out = []
    for mt in G.TILES:
        for nt in G.TILES:
            for kt in G.TILES:
                for s in G.SCALES:
                    c = G.make_cand(M, N, K, mt, nt, kt, s, 1, "Nosplit")
                    if c:
                        out.append(c)
                    g = 2
                    while g * s * s <= NCL:
                        c = G.make_cand(M, N, K, mt, nt, kt, s, g, "splitN")
                        if c and c["n_size"] // (g * s * nt) >= 1:
                            out.append(c)
                        g *= 2
    return out


def space_counts(cands: list[dict], square: bool) -> dict[str, int]:
    out: dict[str, int] = {}
    for c in cands:
        sq = square or c["scale_x"] == c["scale_y"]
        t = "Nosplit" if c["strategy"] == "Nosplit" else f"{c['strategy']}, {'square' if sq else 'non-square'} groups"
        out[t] = out.get(t, 0) + 1
    return out


