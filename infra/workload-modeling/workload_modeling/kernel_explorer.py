# ------------------------------------------------------------------------------------------- HTML
def render_html(ex: Explorer) -> str:
    data = json.dumps(ex.data(), separators=(",", ":")).replace("</", "<\\/")
    return TEMPLATE.read_text().replace("/*__DATA__*/null", data)


def write(ex: Explorer | None = None) -> Explorer:
    ex = ex or Explorer()
    OUT_MD.write_text(render_md(ex))
    OUT_HTML.parent.mkdir(parents=True, exist_ok=True)
    OUT_HTML.write_text(render_html(ex))
    return ex


def main() -> int:
    ex = write()
    bad = [c for c in ex.checks if not c["ok"]]
    print(f"wrote {OUT_MD.relative_to(REPO)}; {OUT_HTML.relative_to(REPO)} (not committed); "
          f"{len(ex.checks) - len(bad)} of {len(ex.checks)} checks pass")
    for c in bad:
        print(f"  FAIL {c['kind']} {c['what']}: {c['detail']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
