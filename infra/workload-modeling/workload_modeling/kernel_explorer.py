"""Kernel mapping explorer: joins the operator graph with the stage-1 kernel runs on H1 (offline).

    python -m workload_modeling.kernel_explorer        (also run by workload_modeling.build)

For every operator of W1 and W1-b it links: operator -> kernel shape -> selected setting -> every swept candidate
-> Perfetto trace, and checks the join:
  1. the selected setting (the one constants.yaml h1_kernels was made from, results/final_h1.csv) is the fastest
     checked run over every result set of that shape (stage-1 sweeps, transposed GEMM, pipelined Eltwise), and its
     time is the one in constants.yaml;
  2. the spatial mapping computed here from the kernel source (SummaGEMM.h / FlatAttentionUtil.h group placement)
     gives the same set of busy clusters as the trace of that setting, where a trace exists;
  3. the per-operator sum reproduces the composed call time of the operator-graph page.
It also splits each matrix kernel's time into ideal compute, padding, idle clusters and the rest (estimate).
Padding has two parts: shape padding (the shape rounded up to whole tiles) and, for GEMM, RedMulE array padding
(each tile rounded up to whole RedMulE output blocks, 32 x 64 on H1, timed as full blocks; see redmule_blocks).

Inputs (all committed): constants.yaml, infra/kernel-runs/results/*.csv, results/trace_summary_h1.json, and the
candidate generators of the kernel-runs drivers (the valid mapping space per shape). Outputs:
docs/analysis/kernel-mapping-h1.md (committed, deterministic) and build/kernel-explorer.html (git-ignored, interactive;
open it through infra/kernel-runs/serve_traces.py to load traces into Perfetto).
"""

