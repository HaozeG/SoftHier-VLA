def render_plan_md(ex: Explorer) -> list[str]:
    """Per page, under the upstream deployment plan: per run key, the selected run (upstream's rule), the
    plan-constrained sweep's pick for the same key (comparison), the recorded fixes and the runs that failed the
    output check."""
    L = []
    for p in ex.pages:
        cmp_ = f"; {p['compare_ms']:.2f} ms {p['compare_label']}" if p.get("compare_ms") else \
            "; plan-constrained sweep not yet composed"
        L += [f"## {p['name']} under the upstream deployment plan", "",
              f"{p['desc']}. Upstream's whole-graph HBM plan (activations west, weights, residual and K/V south; "
              "head-major attention operands written and read by the GEMMs) and its kernel selection (GEMM `opt()` "
              "candidates, both simulated, the faster passing one kept; FlatAttention `attn_auto`; row kernels at "
              f"default parameters). Composed call: {p['sums']['total_ms']} ms, MFU {p['sums']['total']['mfu']} % "
              f"(estimate){cmp_}. Times in µs per call; *constrained* = the plan-constrained sweep's run for the same "
              "key (padded sizes may differ: the attention padding is chosen for the whole graph); x = constrained / "
              "upstream rule.", "",
              "| run key | calls | upstream rule | µs | constrained | µs | x | recorded fix | failed the output check |",
              "| --- | ---: | --- | ---: | --- | ---: | ---: | --- | --- |"]
        for o in sorted({o["kernel"] for o in p["ops"] if o["kernel"]},
                        key=lambda n: (m.STAGES.index(n.split(".")[0]), n)):
            k = ex.kernels[o]
            calls = sum(u["count"] for u in k["uses"] if u["page"] == p["name"])
            alt = k.get("alt", {}).get(p["name"])
            fix = k["selected"].get("fix") or ""
            bad = "; ".join(f"`{f['cand']}` ({int(f['bad']):,} bad)" if f["bad"] else f"`{f['cand']}` ({f['status']})"
                            for f in k["failed"])
            if alt and alt["time_ns"]:
                pad = alt["vid"].split("@", 1)[1] if "@" in alt["vid"] else ""
                same = alt["vid"] == ex._vid(k["name"])
                ac = f"`{alt['cand']}`" + ("" if same else f" @{pad}")
                altc = f"{ac} | {_f(alt['time_ns'] / 1e3, 2)} | {alt['time_ns'] / k['time_ns']:.2f}"
            else:
                altc = "– | – | –"
            L.append(f"| `{k['name']}` | {calls} | `{k['selected']['cand']}` | {_f(k['time_ns'] / 1e3, 2)} | {altc} | "
                     f"{fix or '–'} | {bad or '–'} |")
        L += ["", "`@<sizes>` after a constrained setting: that run uses other padded sizes than upstream's (the "
              "selected attention padding combination).", ""]
    return L


def render_interfaces_md(ex: Explorer) -> list[str]:
    """Per kernel: the tunable parameters parsed from the kernel sources, the values they took over every H1 run of
    that kernel, and the comparison with upstream's frozen interface."""
    L = ["## Kernel parameter interfaces", "",
         "Parsed from the kernel sources (`workload_modeling/kernel_interface.py`: descriptor fields passed to the "
         "entry call, `#if` switches, other macros of the kernel's prefix); kind from its annotation table, which a "
         "test keeps in step with the code both ways. Values: the generated headers in the run folders of every run "
         "of the kernel on H1. Tunable = mapping, schedule, fusion or layout.", "",
         "| kernel | parameter | kind | values over all H1 runs | upstream |", "| --- | --- | --- | --- | --- |"]
    by: dict[str, dict] = {}
    for k in ex.kernels.values():
        kern = k.get("interface_kernel")
        for r in k.get("interface", []):
            e = by.setdefault(kern, {}).setdefault(r["param"], dict(r, seen={}))
            for v, n in r["seen"].items():
                e["seen"][v] = e["seen"].get(v, 0) + n
    for kern in kernel_interface.KERNELS:
        for prm, r in sorted(by.get(kern, {}).items()):
            if r["kind"] not in kernel_interface.TUNABLE:
                continue
            vals = sorted(r["seen"], key=lambda v: -r["seen"][v])
            txt = (", ".join(f"{v}" for v in vals[:8]) + (f" ({len(vals)} values)" if len(vals) > 8 else "")) or "–"
            if len(vals) == 1:
                txt += " (never swept)"
            L.append(f"| {kern} | `{prm}` | {r['kind']} | {txt} | {r.get('upstream') or '–'} |")
    if ex.iface_up:
        ours = set(kernel_interface.KERNELS)
        only = [k for k in ex.iface_up["kernels"] if k not in ours]
        L += ["", f"Upstream (soft_hier_je {ex.iface_up['commit'][:7]}, frozen in "
              "`infra/kernel-runs/results/kernel_interface_upstream.json`): the shared kernels have the same tunable "
              "parameters except those marked *upstream only*; the other differences are output-check switches "
              "(upstream `*_NUMER`, ours `*_CHECK_*`, `GEMM_M/N_VALID`). The kernel code differs where the interface "
              "matches (our SummaGEMM store-range guard, FlatAttention `sqrt_dim`, Activation fixes and GELU). "
              f"Kernel directories only upstream has (`Other`: microbenchmarks), not run here: {', '.join(f'`{k}`' for k in only)} (`RoPE` is "
              "relevant: rope runs here as an Eltwise op).", ""]
    return L


