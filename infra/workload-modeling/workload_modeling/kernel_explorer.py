    L += ["", "Runs that failed the output check but were faster than the selected setting (excluded by the pick "
          "rule; worth a look before trusting the pick):", ""]
    L += [f"* `{n}` / `{w['cand']}`: {w['time_ns']:,} ns, {w['bad']} bad elements, max {w['max_ulp']} ULP"
          for n, w in wf] or ["* none"]
    L += ["", "## Mapping space per GEMM shape", "",
          "Valid settings per technique (the driver's candidate generator: tiles multiples of 32 up to 256, L1 "
          "double buffers within 352 KiB, padded work at most 2.5x) / runs in the sweeps (passing the output check). "
          "A dash: the technique was not enumerated for this shape. Sweep-preset shapes only; W1's plan runs per "
          "key are in the plan section above.", "",
          "| shape | " + " | ".join(t for t, _, _ in GEMM_TECHNIQUES) + " | selected |",
          "| --- | " + " | ".join("---:" for _ in GEMM_TECHNIQUES) + " | --- |"]
    for k in ks:
        if k["kind"] != "gemm" or k["plan"]:
            continue
        by = {t["technique"]: t for t in k["techniques"]}
        cells = []
        for name, _, _ in GEMM_TECHNIQUES:
            t = by.get(name)
            cells.append(f"{t['valid']:,} / {t['swept']} ({t['ok']})" if t and t["enumerated"] else "-")
        L.append(f"| `{k['name']}` | " + " | ".join(cells) + f" | {k['selected']['technique']} |")
    L += ["", "In the kernel but never swept (per shape in the explorer): " + "; ".join(f"{a} ({b})" for a, b in GEMM_NOT_SWEPT)
          + ". Row kernels: Activation's bias_enable (bias added in the same pass) is never run; the bias before GELU "
          "is a separate Eltwise call.", ""]

    L += ["## Row kernels", "",
          "No mapping knob: the kernel spreads the rows over the clusters itself. Effective bandwidth = the "
          "operator's unique bytes / time (HBM peak 1,024 GB/s); busy fractions are means over the active clusters "
          "in the kernel window of the trace.", "",
          "| kernel | used by | time, µs | effective GB/s | active clusters (trace) | iDMA busy | Spatz busy |",
          "| --- | --- | ---: | ---: | ---: | ---: | ---: |"]
    for k in sorted((k for k in ex.kernels.values() if k["kind"] == "row"), key=lambda k: k["name"]):
        uses = ", ".join(sorted({f"{u['stage']}.{u['op']}" for u in k["uses"]}))
        tr = k.get("trace") or {}
        if tr.get("busy_frac"):
            a = tr["active_clusters"]
            mean = lambda u: sum(tr["busy_frac"][u][c] for c in a) / len(a)
            extra = f"{len(a)} | {mean('idma'):.2f} | {mean('spatz'):.2f}"
        else:
            extra = "- | - | -"
        L.append(f"| `{k['name']}` | {uses} | {_f(k['time_ns'] / 1e3, 2)} | {_f(k['hbm_eff_bw'] / 1e9, 0)} | {extra} |")
    L.append("")
    L += render_interfaces_md(ex)
    L += C
    return "\n".join(L)


