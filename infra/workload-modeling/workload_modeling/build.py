"""Generate the stage-1 pages from constants and fixtures (offline).

    python -m workload_modeling.build

Validates constants.yaml, runs the standalone model for the stage-1 workloads, and writes
docs/analysis/stage-totals.md and stage-totals.csv. Re-running on a clean tree gives no diff.
"""

from __future__ import annotations

import csv
import io
import sys
from pathlib import Path

from . import constants
from . import smolvla_ops as m

REPO = Path(__file__).resolve().parents[3]
OUT_DIR = REPO / "docs" / "analysis"
WORKLOADS = ("libero-2cam", "pr1-1cam")
HEADER = "<!-- generated by `python -m workload_modeling.build`; do not edit by hand -->"


def _g(x: float) -> str:
    return f"{x / 1e9:,.3f}"


def _mb(x: float) -> str:
    return f"{x / 1e6:,.1f}"


def _i(x: float | None) -> str:
    return "" if x is None else f"{x:,.0f}"


def stage_rows(c) -> list[dict]:
    out = []
    for wid in WORKLOADS:
        wl = c.workloads[wid]
        d = m.load_dims(wl)
        rows = m.build(c, wid)
        tot = m.stage_totals(rows)
        all_flop = sum(t.flop for t in tot.values())
        for s, t in tot.items():
            out.append({
                "workload": wid, "stage": s,
                "flop": t.flop, "matmul_flop": t.matmul_flop, "flop_share_pct": 100 * t.flop / all_flop,
                "bytes_unique": t.bytes_unique, "bytes_weight": t.bytes_weight, "flop_per_wbyte": t.flop_per_wbyte,
                "_tokens": {"vision": f"{wl.cameras} x {m.vision_tokens(wl, d)}", "connector": f"{wl.cameras * m.vision_tokens(wl, d) // d.shuffle ** 2}",
                            "prefix": f"{m.prefix_tokens(wl, d)}", "expert": f"{d.chunk} x {d.steps} steps"}[s],
            })
    return out


def render_csv(rows: list[dict]) -> str:
    f = io.StringIO()
    cols = ["workload", "stage", "flop", "matmul_flop", "bytes_unique", "bytes_weight", "flop_per_wbyte"]
    w = csv.writer(f, lineterminator="\n")
    w.writerow(cols)
    for r in rows:
        w.writerow([r["workload"], r["stage"], f"{r['flop']:.0f}", f"{r['matmul_flop']:.0f}", f"{r['bytes_unique']:.0f}",
                    f"{r['bytes_weight']:.0f}", "" if r["flop_per_wbyte"] is None else f"{r['flop_per_wbyte']:.2f}"])
    return f.getvalue()


def render_md(c, rows: list[dict]) -> str:
    lines = [
        "# SmolVLA stage totals",
        "",
        HEADER,
        "",
        "Per-stage compute and memory needs of one SmolVLA policy call, from the standalone model "
        "(`infra/workload-modeling/`). The model follows the reference computation (lerobot SmolVLA code) at true "
        "token counts; its matrix-product FLOP agree with PR1's compiled programs within 0.011 % once PR1's padding "
        "and rewrites are applied ([crosscheck.md](crosscheck.md)). Label: inference (model output), cross-checked.",
        "",
        "Conventions ([conventions.md](conventions.md)): fp16 (2 B per element); `bytes_weight` re-reads each "
        "layer's weights once per call and the expert's weights once per flow step; `bytes_unique` adds each "
        "operator's inputs and outputs; FLOP per weight byte = FLOP / `bytes_weight`. Non-matrix FLOP use "
        "per-element conventions.",
        "",
    ]
    for wid in WORKLOADS:
        wl = c.workloads[wid]
        rs = [r for r in rows if r["workload"] == wid]
        tag = " (primary)" if wl.primary else ""
        lines += [
            f"## `{wid}`{tag}",
            "",
            f"Checkpoint `{wl.repo}@{wl.revision[:8]}`; {wl.cameras} camera(s) at {wl.image_size}x{wl.image_size}, "
            f"{wl.language_tokens} language tokens, {wl.state_tokens} state token.",
            "",
            "| stage | tokens | GFLOP | of which matrix | FLOP share % | unique MB | weight MB | FLOP per weight byte |",
            "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |",
        ]
        for r in rs:
            lines.append(f"| {r['stage']} | {r['_tokens']} | {_g(r['flop'])} | {_g(r['matmul_flop'])} | "
                         f"{r['flop_share_pct']:.1f} | {_mb(r['bytes_unique'])} | {_mb(r['bytes_weight'])} | "
                         f"{_i(r['flop_per_wbyte'])} |")
        tf = sum(r["flop"] for r in rs)
        tw = sum(r["bytes_weight"] for r in rs)
        lines += [f"| **total** | | {_g(tf)} | {_g(sum(r['matmul_flop'] for r in rs))} | 100.0 | "
                  f"{_mb(sum(r['bytes_unique'] for r in rs))} | {_mb(tw)} | {_i(tf / tw)} |", ""]
        e = next(r for r in rs if r["stage"] == "expert")
        steps = m.load_dims(wl).steps
        lines += [f"Expert per flow step: {_g(e['flop'] / steps)} GFLOP, {_mb(e['bytes_weight'] / steps)} MB of weights "
                  f"(includes the cross-attention K/V projection, which the reference code repeats every step).", ""]
    thor = c.value("thor.fp16_dense") * 1e12 / (c.value("thor.dram_bw") * 1e9)
    lines += [
        "## Reading against a machine balance",
        "",
        f"A stage whose FLOP per weight byte is below a machine's peak FLOP/s divided by its memory bandwidth is limited "
        f"by streaming weights at batch size 1, if weights cannot stay on chip. For Jetson Thor that balance is "
        f"`thor.fp16_dense` / `thor.dram_bw` = {thor:,.0f} FLOP per byte (inference). The SoftHier balance depends on "
        f"the HBM bandwidth, which is an open parameter ([hw-config.md](hw-config.md)).",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    c = constants.load()
    rows = stage_rows(c)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "stage-totals.md").write_text(render_md(c, rows))
    (OUT_DIR / "stage-totals.csv").write_text(render_csv(rows))
    print(f"wrote {OUT_DIR.relative_to(REPO)}/stage-totals.md, stage-totals.csv")
    return 0


if __name__ == "__main__":
    sys.exit(main())
