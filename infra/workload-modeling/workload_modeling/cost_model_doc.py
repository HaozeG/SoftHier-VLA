COLORS = {"M = 50": "#2a78c8", "M = 192, 241": "#d0731c", "M >= 1024": "#2f9e5b"}


def _cls(shape: str) -> str:
    m = _shape(shape)[0]
    return "M = 50" if m == 50 else ("M = 192, 241" if m < 1024 else "M >= 1024")


def scatter_svg(d: Data) -> str:
    """Model time vs measured time of every checked GEMM run, log-log, with the y = x line and 2x / 4x guides."""
    W, H, L, R, T, B = 640, 460, 64, 150, 20, 52
    lo, hi = 1e2, 1e6
    X = lambda v: L + (math.log10(v) - math.log10(lo)) / (math.log10(hi) - math.log10(lo)) * (W - L - R)   # noqa
    Y = lambda v: H - B - (math.log10(v) - math.log10(lo)) / (math.log10(hi) - math.log10(lo)) * (H - T - B)  # noqa
    s = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" role="img" font-family="system-ui, sans-serif" '
         f'font-size="12" aria-label="Model time against measured time for {len(d.runs)} checked GEMM runs on H1: '
         'points sit above the y = x line, the model is optimistic, most for M = 50">',
         '<rect width="100%" height="100%" fill="#ffffff"/>']
    for e in range(2, 7):
        v = 10 ** e
        s.append(f'<line x1="{X(v):.1f}" y1="{T}" x2="{X(v):.1f}" y2="{H - B}" stroke="#d8dde3"/>')
        s.append(f'<line x1="{L}" y1="{Y(v):.1f}" x2="{W - R}" y2="{Y(v):.1f}" stroke="#d8dde3"/>')
        lab = {2: "0.1", 3: "1", 4: "10", 5: "100", 6: "1000"}[e]
        s.append(f'<text x="{X(v):.1f}" y="{H - B + 16}" text-anchor="middle" fill="#40464d">{lab}</text>')
        s.append(f'<text x="{L - 6}" y="{Y(v) + 4:.1f}" text-anchor="end" fill="#40464d">{lab}</text>')
    for k, dash in ((1, ""), (2, ' stroke-dasharray="4 3"'), (4, ' stroke-dasharray="1 3"')):
        x0, x1 = lo, hi / k
        s.append(f'<line x1="{X(x0):.1f}" y1="{Y(x0 * k):.1f}" x2="{X(x1):.1f}" y2="{Y(x1 * k):.1f}" '
                 f'stroke="#1f2328" stroke-width="1"{dash}/>')
        s.append(f'<text x="{X(x1) - 4:.1f}" y="{Y(x1 * k) + 14:.1f}" text-anchor="end" fill="#1f2328">'
                 f'{"measured = model" if k == 1 else f"{k}x"}</text>')
    for x in sorted(d.runs, key=lambda x: _cls(x["shape"])):
        c = COLORS[_cls(x["shape"])]
        s.append(f'<circle cx="{X(x["model"]):.1f}" cy="{Y(x["t"]):.1f}" r="3" fill="{c}" fill-opacity="0.7">'
                 f'<title>{x["shape"]} {x["cand"]}: model {x["model"] / 1e3:.2f} us, measured {x["t"] / 1e3:.2f} us'
                 f'</title></circle>')
    s.append(f'<text x="{(L + W - R) / 2:.0f}" y="{H - 12}" text-anchor="middle" fill="#1f2328">'
             'model time, us (kernel_model, log)</text>')
    s.append(f'<text transform="translate(16 {(T + H - B) / 2:.0f}) rotate(-90)" text-anchor="middle" '
             'fill="#1f2328">measured time, us (GVSoC, log)</text>')
    for i, (k, c) in enumerate(COLORS.items()):
        n = sum(_cls(x["shape"]) == k for x in d.runs)
        y = T + 14 + 20 * i
        s.append(f'<circle cx="{W - R + 16}" cy="{y - 4}" r="4" fill="{c}"/>'
                 f'<text x="{W - R + 26}" y="{y}" fill="#1f2328">{k} ({n})</text>')
    s.append("</svg>")
    return "\n".join(s)


