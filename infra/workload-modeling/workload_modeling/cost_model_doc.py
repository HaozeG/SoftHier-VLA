def _rows(name: str) -> list[dict]:
    p = RES / name
    return list(csv.DictReader(p.open())) if p.exists() else []


def _drivers():
    if str(KR) not in sys.path:
        sys.path.insert(0, str(KR))
    import attn_sweep, gemm_sweep, gemm_upstream  # noqa: E401
    return gemm_sweep, gemm_upstream, attn_sweep


def _shape(s: str) -> list[int]:
    return [int(x) for x in s.split("x")]


def _setting(r: dict) -> tuple:
    sx = int(r.get("scale_x") or r.get("scale")); sy = int(r.get("scale_y") or r.get("scale"))
    return (int(r["m_size"]), int(r["n_size"]), int(r["k_size"]), int(r["m_tile"]), int(r["n_tile"]),
            int(r["k_tile"]), sx, sy, int(r["groups"]), r["strategy"])


def earlier_model(r: dict) -> float:
    """The ranking model gemm_sweep.py / gemm_smallm_sweep.py used before kernel_model (for the comparison only):
    1,024 MAC/cycle whatever the tile, 150 ns per call, 300 ns per splitK reduction step, HBM 200 B/ns."""
    Mp, Np, Kp, mt, nt, kt, sx, sy, g, st = _setting(r)
    m_it = Mp // (sy * mt)
    n_it = Np // (sx * nt) // (g if st == "splitN" else 1)
    Kg = Kp // g if st == "splitK" else Kp
    t = m_it * n_it * (Kg // kt) * (mt * nt * kt / 1024.0 + 150.0) + (m_it * n_it * 300.0 if st == "splitK" else 0)
    return max(t, (g * m_it * n_it * 2 * Kg * (sy * mt + sx * nt) + 2 * Mp * Np) / 200.0)


def _ranks(v):
    o = sorted(range(len(v)), key=lambda i: v[i]); r = [0] * len(v)
    for k, i in enumerate(o):
        r[i] = k
    return r


def spearman(a, b) -> float:
    ra, rb = _ranks(a), _ranks(b); n = len(a)
    return 1 - 6 * sum((x - y) ** 2 for x, y in zip(ra, rb)) / (n * (n * n - 1))


# ------------------------------------------------------------------------------------------- data
class Data:
    def __init__(self, c: constants.Constants | None = None):
        self.c = c or constants.load()
        self.A = km.arch(self.c)
        self.G, self.U, self.At = _drivers()
        self.final = {r["name"]: r for r in _rows("final_h1.csv")}
        runs = []
        for name, src in (("gemm_sweep_h1.csv", "gemm_sweep"), ("gemm_smallm_h1.csv", "gemm_smallm_sweep"),
                          ("gemm_upstream_h1.csv", "gemm_upstream"), ("gemm_transpose_h1.csv", "gemm_transpose")):
            for r in _rows(name):
                if r["status"] != "ok":
                    continue
                shape = r.get("orig_shape") or r["shape"]
                runs.append(dict(src=src, shape=shape, cand=("T:" if src == "gemm_transpose" else "") + r["cand"],
                                 t=int(r["time_ns"]), model=km.gemm_ns(*_setting(r), self.A)["est_ns"],
                                 old=earlier_model(r), r=r))
        # one entry per distinct run (gemm_upstream reuses gemm_sweep runs of identical settings)
        seen, self.runs = set(), []
        for x in runs:
            if x["r"].get("run_dir") not in seen:
                seen.add(x["r"].get("run_dir")); self.runs.append(x)
        self.shapes = sorted({x["shape"] for x in self.runs if x["src"] != "gemm_transpose"}, key=_shape)
        self.up = _rows("gemm_upstream_h1.csv")

    def best(self, shape: str) -> int:
        return int(self.final[f"gemm_{shape}"]["time_ns"])

    def per_shape(self):
        """Per shape (runs on the operator's own shape, transposed runs left out): rank correlation of each model
        with the measured times, and the measured time of each model's top choice over the best."""
        out = []
        for sh in self.shapes:
            xs = [x for x in self.runs if x["shape"] == sh and x["src"] != "gemm_transpose"]
            if len(xs) < 4:
                continue
            t = [x["t"] for x in xs]
            b = min(t)
            top = lambda key: min(xs, key=lambda x: x[key])["t"] / b       # noqa: E731
            bx = min(xs, key=lambda x: x["t"])
            out.append(dict(shape=sh, n=len(xs), rho_old=spearman([x["old"] for x in xs], t),
                            rho_new=spearman([x["model"] for x in xs], t), top_old=top("old"), top_new=top("model"),
                            ratio=bx["t"] / bx["model"]))
        return out


